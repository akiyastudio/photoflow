const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const manager = fs.readFileSync(path.join(root, 'renderer/src/legacy/PersonIdentityManager.tsx'), 'utf8');
const photoManager = fs.readFileSync(path.join(root, 'renderer/src/legacy/TeamRetouchManager.tsx'), 'utf8');
const progressHook = fs.readFileSync(path.join(root, 'renderer/src/legacy/useTeamOutputProgress.ts'), 'utf8');
const dialog = fs.readFileSync(path.join(root, 'renderer/src/legacy/legacy-dialog.tsx'), 'utf8');
const layer = fs.readFileSync(path.join(root, 'renderer/src/legacy/legacy-layer.ts'), 'utf8');
assert.equal(manager.includes("tab === 'people'"), false, 'the unreachable people tab is removed');
assert.equal(manager.includes('data-merge-audit'), false, 'the hidden duplicate merge audit is removed');
for (const text of ['任务分配', '批量导入返图', '审核输出', '重新输出']) assert(manager.includes(text), `current workflow action remains: ${text}`);
assert(photoManager.includes('调整工作图范围') && photoManager.includes('下一步：'));
for (const contract of ['aria-busy={cropBusy}', 'disabled={cropBusy}', 'disabled={cropBusy} onClick={() => setCropEditor(null)}', 'disabled={cropBusy} onChange=']) assert(photoManager.includes(contract), `busy crop editor contract remains wired: ${contract}`);
assert(dialog.includes('aria-modal="true"') && dialog.includes('pf-dialog-title'));
assert.equal((layer.match(/window\.addEventListener\('keydown'/g) || []).length, 1, 'one registry owns modal keyboard handling');
for (const source of [manager, photoManager, progressHook]) assert.equal(source.includes('@ts-nocheck'), false);
const distAssets = path.join(root, 'dist/ui/assets');
const builtMain = fs.readdirSync(distAssets).filter(name => /^main-.*\.js$/u.test(name)).map(name => fs.readFileSync(path.join(distAssets, name), 'utf8')).join('\n');
for (const text of ['任务分配', '批量导入返图', '审核输出', '重新输出']) assert(builtMain.includes(text), `built renderer retains current workflow action: ${text}`);
console.log('Team-retouch C2 renderer contracts passed');
