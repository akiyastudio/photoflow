const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { PREPARE_STEPS, writeSessionLogBestEffort } = require('./prepare-release.cjs');
const { writeQualityReceipt, validateQualityReceipt, clearQualityReceipt, readGitHead, assertGitHead, captureGitSourceFence, assertGitSourceFence, assertCleanGitWorktree } = require('./release-quality-receipt.cjs');

const root = path.resolve(__dirname, '..');
const packageJson = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
assert.deepEqual(PREPARE_STEPS, ['check:release:quality', 'electron:build', 'build:components']);
assert.equal(packageJson.scripts['release:prepare'], 'node scripts/prepare-release.cjs');
assert.equal(packageJson.scripts['check:release:quality'], 'node scripts/check-project.cjs --release-quality');
assert.equal(packageJson.scripts['check:release:final'], 'node scripts/check-final-release-ready.cjs');
const finalSource = fs.readFileSync(path.join(root, 'scripts', 'check-final-release-ready.cjs'), 'utf8');
assert(finalSource.indexOf('verifyStagedRelease(') < finalSource.indexOf('test-legal-release-evidence.cjs'), 'final must hash the stable artifact set before checking approval');
assert(finalSource.includes("'--delivery-manifest', evidence.manifestPath") && finalSource.includes('assertStagedReleaseUnchanged(evidence)'), 'final approval must bind and fence the stable manifest');
assert(finalSource.includes('acquireReleaseLock(root)') && finalSource.includes('releaseLock(lock)'), 'final must share the release lock');
const publishSource = fs.readFileSync(path.join(root, 'scripts', 'publish-release.cjs'), 'utf8');
assert(publishSource.indexOf('verifyStagedRelease(') < publishSource.indexOf('let token = String(process.env.PHOTOFLOW_ADMIN_TOKEN'), 'publish must hash stable artifacts before reading a token');
assert(publishSource.includes("'--delivery-manifest', manifestPath") && publishSource.includes('assertStagedReleaseUnchanged(stagedEvidence)'), 'publish approval must bind and fence the stable manifest');
assert(publishSource.includes('acquireReleaseLock(repositoryRoot)') && publishSource.includes('releaseLock(releaseLockHandle)'), 'publish must hold the release lock across interactive and network work');
const releaseJsonSource = fs.readFileSync(path.join(root, 'scripts', 'generate-release-json.cjs'), 'utf8');
assert(releaseJsonSource.includes('captureArtifactIdentity(installerPath)') && releaseJsonSource.indexOf('assertSourceIdentity(installerPath, installerIdentity)') < releaseJsonSource.indexOf('await publishRelease(record)'), 'release record publishing must retain the approved installer identity fence through network publication');
assert(releaseJsonSource.includes('release:json 只能生成未发布草稿'), 'direct release:json must reject published or network modes');
assert(publishSource.indexOf('await publishReleaseOnce(') < publishSource.indexOf('fs.renameSync(temporaryPath, outputPath)'), 'prepared published evidence must only be promoted after confirmed remote success');
const fixtureRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'photoflow-release-receipt-'));
try {
  const blockedLogRoot = path.join(fixtureRoot, 'not-a-directory'); fs.writeFileSync(blockedLogRoot, 'file');
  assert.equal(writeSessionLogBestEffort(blockedLogRoot, 'attempt', {}, () => {}), false, 'session log failure must not invalidate successful immutable staging');
  fs.rmSync(blockedLogRoot);
  const git = args => { const result = spawnSync('git', args, { cwd: fixtureRoot, encoding: 'utf8', windowsHide: true }); assert.equal(result.status, 0, result.stderr); };
  git(['init', '--quiet']);
  fs.writeFileSync(path.join(fixtureRoot, 'component.json'), '{}');
  fs.writeFileSync(path.join(fixtureRoot, '.gitignore'), 'artifacts/\n');
  git(['add', 'component.json', '.gitignore']);
  git(['-c', 'user.name=PhotoFlow Test', '-c', 'user.email=test@photoflow.invalid', 'commit', '--quiet', '-m', 'fixture']);
  assert.equal(assertCleanGitWorktree(fixtureRoot).status, 'clean');
  const quality = writeQualityReceipt({ repositoryRoot: fixtureRoot, gitCommit: 'a'.repeat(40), attemptId: '11111111-1111-4111-8111-111111111111', startedAt: '2026-01-01T00:00:00.000Z', finishedAt: '2026-01-01T00:01:00.000Z' });
  assert.equal(validateQualityReceipt({ repositoryRoot: fixtureRoot, gitCommit: 'a'.repeat(40), now: Date.parse('2026-01-01T00:01:01.000Z') }).status, 'observed-passed');
  assert.equal(quality.trust, 'informational');
  assert.equal(quality.command, 'npm run check:release:quality');
  fs.writeFileSync(path.join(fixtureRoot, 'component.json'), '{"dirty":true}');
  assert.throws(() => assertCleanGitWorktree(fixtureRoot), /未提交|构建输入/);
  git(['checkout', '--', 'component.json']);
  assert.throws(() => validateQualityReceipt({ repositoryRoot: fixtureRoot, gitCommit: 'b'.repeat(40), now: Date.parse('2026-01-01T00:01:01.000Z') }), /不对应当前 HEAD/);
  const startHead = readGitHead(fixtureRoot);
  const sourceFence = captureGitSourceFence(fixtureRoot);
  fs.writeFileSync(path.join(fixtureRoot, 'component.json'), '{"next":true}');
  git(['add', 'component.json']);
  git(['-c', 'user.name=PhotoFlow Test', '-c', 'user.email=test@photoflow.invalid', 'commit', '--quiet', '-m', 'next']);
  assert.equal(assertCleanGitWorktree(fixtureRoot).status, 'clean');
  assert.throws(() => assertGitHead(fixtureRoot, startHead), /HEAD 已变化/);
  git(['checkout', '--quiet', '--detach', startHead]);
  assert.equal(readGitHead(fixtureRoot), startHead);
  assert.throws(() => assertGitSourceFence(fixtureRoot, sourceFence), /Git 元数据发生变化/);
  clearQualityReceipt(fixtureRoot);
  assert.throws(() => validateQualityReceipt({ repositoryRoot: fixtureRoot, gitCommit: readGitHead(fixtureRoot) }), /回执缺失/);
} finally { fs.rmSync(fixtureRoot, { recursive: true, force: true }); }
console.log('Release workflow ordering tests passed.');
